export async function loadProjectAction(projectId: string): Promise<LoadProjectResult> {
  const user = await requireUser();
  const supabase = await createClient();
  const projects = await projectsClientForCurrentUser();
  const projectAssets = await projectAssetsClientForCurrentUser();
  return loadProject(projects, supabase.storage, user.id, projectId, projectAssets);
}
