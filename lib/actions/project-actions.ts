/**
 * Minimal persistence layer for the real generation pipeline — reuses the
 * existing public.projects table (004_projects_video_jobs.sql) rather than
 * a new one; only supabase/migrations/016_projects_narration_audio.sql's
 * one new `narration` column was needed. Every one of these thin wrappers
 * adds auth + the real, authenticated (RLS-scoped, never service-role)
 * Supabase client and delegates to lib/actions/project-persistence.ts's
 * plain, unit-tested functions — same split as narration-actions.ts vs
 * plan-narration.ts. `projectId` is a plain parameter here, never a
 * security boundary by itself: every query is scoped to
 * `owner_id = user.id` both by the table's RLS policy AND explicitly in
 * the adapter below.
 */
/** Exported so lib/actions/export-actions.ts (which also needs to loadProject as part of starting an export) can reuse the exact same adapter instead of redeclaring it. */
export async function projectsClientForCurrentUser(): Promise<ProjectsClient> {
  const supabase = await createClient();

  return {
    async insertProject(row: NewProjectRow) {
      const { data, error } = await supabase.from("projects").insert(row).select("id").single();
      if (error || !data) return { ok: false, error: error?.message ?? "Failed to save the project." };
      return { ok: true, id: data.id };
    },
    async updateProject(projectId, ownerId, patch) {
      const { error } = await supabase.from("projects").update(patch).eq("id", projectId).eq("owner_id", ownerId);
      if (error) return { ok: false, error: error.message };
      return { ok: true };
    },
    async selectProject(projectId, ownerId): Promise<ProjectRow | null> {
      const { data } = await supabase
        .from("projects")
        .select("id, prompt, scene_plan, narration")
        .eq("id", projectId)
        .eq("owner_id", ownerId)
        .maybeSingle();
      return data;
    },
  };
}

/** Exported so lib/actions/visual-actions.ts and export-actions.ts can reuse the exact same adapter instead of redeclaring it — mirrors projectsClientForCurrentUser above. */
export async function projectAssetsClientForCurrentUser(): Promise<ProjectAssetsClient> {
  const supabase = await createClient();

  return {
    async insertVisualAsset(row) {
      const { error } = await supabase.from("project_assets").insert({
        project_id: row.project_id,
        owner_id: row.owner_id,
        kind: row.kind,
        scene_id: row.scene_id,
        storage_path: row.storage_path,
        mime_type: row.mime_type,
        metadata: row.metadata,
      });
      if (error) return { ok: false, error: error.message };
      return { ok: true };
    },
    async listAutoGeneratedVisuals(projectId, ownerId) {
      const { data } = await supabase
        .from("project_assets")
        .select("scene_id, storage_path, metadata")
        .eq("project_id", projectId)
        .eq("owner_id", ownerId)
        .eq("kind", "auto-generated");
      return (data ?? []).map((row) => {
        const metadata = (row.metadata ?? {}) as { prompt?: string; provider?: string; estimatedUsd?: number | null };
        return { scene_id: row.scene_id, storage_path: row.storage_path, provider: metadata.provider ?? null, prompt: metadata.prompt ?? null, estimated_usd: metadata.estimatedUsd ?? null };
      });
    },
    async insertVideoAsset(row) {
      const { error } = await supabase.from("project_assets").insert({
        project_id: row.project_id,
        owner_id: row.owner_id,
        kind: row.kind,
        scene_id: row.scene_id,
        storage_path: row.storage_path,
        mime_type: row.mime_type,
        metadata: row.metadata,
      });
      if (error) return { ok: false, error: error.message };
      return { ok: true };
    },
    async listAiVideos(projectId, ownerId) {
      const { data } = await supabase
        .from("project_assets")
        .select("scene_id, storage_path, metadata")
        .eq("project_id", projectId)
        .eq("owner_id", ownerId)
        .eq("kind", "ai-video");
      return (data ?? []).map((row) => {
        const metadata = (row.metadata ?? {}) as {
          provider?: string;
          model?: string;
          providerTaskId?: string;
          durationSeconds?: number;
          motionPrompt?: string;
          providerCost?: number | null;
        };
        return {
          scene_id: row.scene_id,
          storage_path: row.storage_path,
          provider: metadata.provider ?? null,
          model: metadata.model ?? null,
          provider_task_id: metadata.providerTaskId ?? null,
          duration_seconds: metadata.durationSeconds ?? null,
          motion_prompt: metadata.motionPrompt ?? null,
          provider_cost: metadata.providerCost ?? null,
        };
      });
    },
  };
}

export async function saveGeneratedProjectAction(prompt: string, plan: VideoPlan): Promise<SaveProjectResult> {
  const user = await requireUser();
  const projects = await projectsClientForCurrentUser();
  return saveGeneratedProject(projects, realEntitlementClient(), user.id, prompt, plan);
}

