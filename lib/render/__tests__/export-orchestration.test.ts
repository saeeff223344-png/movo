function makeFakeProjectsClient() {
  const rows = new Map<string, ProjectRow & { owner_id: string }>();
  let nextId = 1;
  const client: ProjectsClient = {
    async insertProject(row) {
      const id = `project-${nextId++}`;
      rows.set(id, { id, prompt: row.prompt, scene_plan: row.scene_plan, narration: null, owner_id: row.owner_id });
      return { ok: true, id };
    },
    async updateProject(projectId, ownerId, patch) {
      const existing = rows.get(projectId);
      if (!existing || existing.owner_id !== ownerId) return { ok: false, error: "not found or not owned" };
      rows.set(projectId, { ...existing, ...patch });
      return { ok: true };
    },
    async selectProject(projectId, ownerId) {
      const existing = rows.get(projectId);
      if (!existing || existing.owner_id !== ownerId) return null;
      const { owner_id: _owner_id, ...row } = existing;
      return row;
    },
  };
  return { client, rows };
}

