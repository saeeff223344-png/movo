function makeFakeRenderJobsClient() {
  const rows = new Map<string, RenderJobRow & { user_id: string }>();
  let nextId = 1;
  const client: RenderJobsClient = {
    async insertRenderJob(row) {
      const id = `job-${nextId++}`;
      rows.set(id, { id, project_id: row.project_id, video_id: row.video_id, status: row.status, progress: 0, server: row.server, error_message: null, user_id: row.user_id });
      return { ok: true, id };
    },
    async updateRenderJob(id, ownerId, patch) {
      const existing = rows.get(id);
      if (!existing || existing.user_id !== ownerId) return { ok: false, error: "not found or not owned" };
      rows.set(id, { ...existing, ...patch });
      return { ok: true };
    },
    async selectRenderJob(id, ownerId) {
      const existing = rows.get(id);
      if (!existing || existing.user_id !== ownerId) return { ok: true, job: null };
      return { ok: true, job: existing };
    },
    async hasActiveJobForProject(ownerId, projectId) {
      for (const row of rows.values()) {
        if (row.user_id === ownerId && row.project_id === projectId && (row.status === "queued" || row.status === "processing")) return true;
      }
      return false;
    },
  };
  return { client, rows };
}

